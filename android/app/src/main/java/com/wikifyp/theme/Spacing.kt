package com.wikifyp.theme

import androidx.compose.ui.unit.dp

// Spacing tokens, a single 4dp-based scale. Use these instead of raw dp so
// screens stay on one rhythm.
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
    val xxl = 48.dp
}
